#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Dart文件自动格式化脚本
用于遍历lib目录下的所有Dart文件，使用dart format命令进行自动格式化
"""

import os
import sys
import logging
import subprocess
import re
from pathlib import Path
from typing import List, Tuple, Optional, Set
import time

# 配置日志
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('format_file.log', encoding='utf-8'),
        logging.StreamHandler(sys.stdout)
    ]
)

logger = logging.getLogger(__name__)

class DartFileFormatter:
    """Dart文件自动格式化器"""
    
    # 定义需要跳过的文件和模式
    SKIP_PATTERNS = {
        # 自动生成的文件后缀
        '*.g.dart',           # 代码生成文件
        '*.freezed.dart',     # Freezed生成文件
        '*.mocks.dart',       # Mock生成文件
        '*.config.dart',      # 配置生成文件
        
        # 特定文件名
        'MyLocalization.dart',  # 本地化文件
        'firebase_options.dart',  # Firebase配置文件
        
        # 包含特定内容的文件（需要读取文件内容检查）
        '// GENERATED CODE',     # 生成代码标识
        '// 该文件由.*自动生成',   # 中文生成标识
        '// Generated by',      # 英文生成标识
        '// This file is generated',  # 另一种生成标识
    }
    
    def __init__(self, lib_path: str):
        """
        初始化格式化器
        
        Args:
            lib_path: lib目录的绝对路径
        """
        self.lib_path = Path(lib_path)
        self.processed_files = 0
        self.failed_files = 0
        self.skipped_files = 0
        self.changed_files = 0
        self.filtered_files = 0  # 被过滤的文件数
        self.dart_cmd = self._find_dart_command()
        
        if not self.lib_path.exists():
            raise FileNotFoundError(f"lib目录不存在: {lib_path}")
        
        if not self.lib_path.is_dir():
            raise NotADirectoryError(f"指定路径不是目录: {lib_path}")
    
    def _find_dart_command(self) -> Optional[str]:
        """
        查找dart命令
        
        Returns:
            dart命令的路径，如果未找到则返回None
        """
        try:
            result = subprocess.run(['which', 'dart'], 
                                  capture_output=True, 
                                  text=True, 
                                  timeout=10)
            if result.returncode == 0:
                dart_path = result.stdout.strip()
                logger.info(f"找到dart命令: {dart_path}")
                return dart_path
            else:
                logger.error("未找到dart命令")
                return None
        except Exception as e:
            logger.error(f"查找dart命令失败: {e}")
            return None
    
    def _should_skip_file(self, file_path: Path) -> Tuple[bool, str]:
        """
        检查文件是否应该被跳过
        
        Args:
            file_path: 文件路径
            
        Returns:
            (是否跳过, 跳过原因)
        """
        # 检查文件名模式
        file_name = file_path.name
        
        # 检查特定文件名
        if file_name in ['MyLocalization.dart', 'firebase_options.dart']:
            return True, f"特定文件名: {file_name}"
        
        # 检查文件后缀模式
        if file_name.endswith('.g.dart'):
            return True, "代码生成文件(.g.dart)"
        if file_name.endswith('.freezed.dart'):
            return True, "Freezed生成文件(.freezed.dart)"
        if file_name.endswith('.mocks.dart'):
            return True, "Mock生成文件(.mocks.dart)"
        if file_name.endswith('.config.dart'):
            return True, "配置生成文件(.config.dart)"
        
        # 检查文件内容是否包含生成标识
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                # 只读取前几行来检查生成标识
                first_lines = []
                for i, line in enumerate(f):
                    if i >= 10:  # 只检查前10行
                        break
                    first_lines.append(line.strip())
                
                content_start = '\n'.join(first_lines)
                
                # 检查各种生成标识
                if '// GENERATED CODE' in content_start:
                    return True, "包含生成代码标识(GENERATED CODE)"
                if re.search(r'// 该文件由.*自动生成', content_start):
                    return True, "包含中文生成标识"
                if '// Generated by' in content_start:
                    return True, "包含生成标识(Generated by)"
                if '// This file is generated' in content_start:
                    return True, "包含生成标识(This file is generated)"
                if '// Code generated by' in content_start:
                    return True, "包含生成标识(Code generated by)"
                
        except Exception as e:
            logger.debug(f"检查文件内容时出错 {file_path}: {e}")
            # 如果无法读取文件内容，不跳过
            pass
        
        return False, ""
    
    def find_dart_files(self) -> List[Path]:
        """
        递归查找所有需要格式化的Dart文件（排除自动生成的文件）
        
        Returns:
            需要格式化的Dart文件路径列表
        """
        dart_files = []
        total_files = 0
        
        logger.info(f"开始扫描目录: {self.lib_path}")
        
        for file_path in self.lib_path.rglob("*.dart"):
            total_files += 1
            
            # 跳过隐藏文件和临时文件
            if any(part.startswith('.') for part in file_path.parts):
                logger.debug(f"跳过隐藏文件: {file_path}")
                self.filtered_files += 1
                continue
            
            # 检查是否应该跳过这个文件
            should_skip, skip_reason = self._should_skip_file(file_path)
            if should_skip:
                logger.debug(f"跳过文件: {file_path.relative_to(self.lib_path)} ({skip_reason})")
                self.filtered_files += 1
                continue
                
            if file_path.suffix.lower() == '.dart':
                dart_files.append(file_path)
        
        logger.info(f"扫描完成:")
        logger.info(f"  总Dart文件数: {total_files}")
        logger.info(f"  过滤的文件数: {self.filtered_files}")
        logger.info(f"  需要处理的文件数: {len(dart_files)}")
        
        return dart_files
    
    def format_file(self, file_path: Path) -> Tuple[bool, str, bool]:
        """
        使用dart format格式化单个Dart文件
        
        Args:
            file_path: 文件路径
            
        Returns:
            (是否成功, 错误信息, 文件是否被修改)
        """
        try:
            # 检查文件是否为空
            if file_path.stat().st_size == 0:
                logger.warning(f"文件为空，跳过: {file_path}")
                self.skipped_files += 1
                return True, "文件为空", False
            
            # 先检查文件是否需要格式化（使用--set-exit-if-changed标志）
            check_result = subprocess.run([
                self.dart_cmd, 'format', 
                '--set-exit-if-changed',
                '--output=none',
                str(file_path)
            ], capture_output=True, text=True, timeout=30)
            
            # 退出码1表示文件需要格式化，0表示已经格式化好了
            needs_formatting = check_result.returncode == 1
            
            if not needs_formatting:
                logger.debug(f"文件已格式化，跳过: {file_path}")
                self.skipped_files += 1
                return True, "已格式化", False
            
            # 执行格式化
            format_result = subprocess.run([
                self.dart_cmd, 'format', 
                '--output=write',
                str(file_path)
            ], capture_output=True, text=True, timeout=30)
            
            if format_result.returncode == 0:
                logger.debug(f"成功格式化: {file_path}")
                self.processed_files += 1
                self.changed_files += 1
                return True, "", True
            else:
                error_msg = f"格式化失败: {format_result.stderr}"
                logger.error(f"格式化文件失败 {file_path}: {error_msg}")
                self.failed_files += 1
                return False, error_msg, False
                
        except subprocess.TimeoutExpired:
            error_msg = "格式化超时"
            logger.error(f"格式化文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
            
        except PermissionError as e:
            error_msg = f"权限错误: {e}"
            logger.error(f"格式化文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
            
        except Exception as e:
            error_msg = f"未知错误: {e}"
            logger.error(f"格式化文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
    
    def batch_format_directory(self) -> Tuple[bool, str]:
        """
        批量格式化目录（排除自动生成的文件）
        
        Returns:
            (是否成功, 错误信息)
        """
        try:
            logger.info(f"开始批量格式化目录: {self.lib_path}")
            
            # 获取需要格式化的文件列表
            dart_files = self.find_dart_files()
            
            if not dart_files:
                logger.warning("没有找到需要格式化的Dart文件")
                return True, "无文件需要处理"
            
            # 构建dart format命令，传入具体的文件列表
            file_paths = [str(file_path) for file_path in dart_files]
            
            # 检查是否需要格式化
            check_cmd = [self.dart_cmd, 'format', '--set-exit-if-changed', '--output=none'] + file_paths
            
            format_result = subprocess.run(
                check_cmd,
                capture_output=True, 
                text=True, 
                timeout=120
            )
            
            if format_result.returncode == 0:
                logger.info("批量格式化完成，没有文件需要修改")
                return True, "无需修改"
            elif format_result.returncode == 1:
                logger.info("检测到需要格式化的文件，开始应用格式化")
                
                # 应用格式化
                apply_cmd = [self.dart_cmd, 'format'] + file_paths
                apply_result = subprocess.run(
                    apply_cmd,
                    capture_output=True, 
                    text=True, 
                    timeout=120
                )
                
                if apply_result.returncode == 0:
                    logger.info("批量格式化应用成功")
                    return True, "格式化成功"
                else:
                    error_msg = f"应用格式化失败: {apply_result.stderr}"
                    logger.error(error_msg)
                    return False, error_msg
            else:
                error_msg = f"批量格式化检查失败: {format_result.stderr}"
                logger.error(error_msg)
                return False, error_msg
                
        except subprocess.TimeoutExpired:
            error_msg = "批量格式化超时"
            logger.error(error_msg)
            return False, error_msg
            
        except Exception as e:
            error_msg = f"批量格式化异常: {e}"
            logger.error(error_msg)
            return False, error_msg
    
    def run(self, use_batch_mode: bool = True) -> bool:
        """
        执行格式化任务
        
        Args:
            use_batch_mode: 是否使用批量模式（推荐）
        
        Returns:
            是否成功完成所有任务
        """
        start_time = time.time()
        logger.info("="*60)
        logger.info("开始执行Dart文件自动格式化任务")
        logger.info("="*60)
        
        if not self.dart_cmd:
            logger.error("dart命令不可用，无法执行格式化")
            return False
        
        try:
            if use_batch_mode:
                # 使用批量模式，更高效
                logger.info("使用批量格式化模式")
                success, error_msg = self.batch_format_directory()
                
                if success:
                    end_time = time.time()
                    duration = end_time - start_time
                    
                    logger.info("="*60)
                    logger.info("批量格式化完成统计:")
                    logger.info(f"处理目录: {self.lib_path}")
                    logger.info(f"过滤的文件数: {self.filtered_files}")
                    logger.info(f"状态: {error_msg}")
                    logger.info(f"耗时: {duration:.2f}秒")
                    logger.info("="*60)
                    
                    return True
                else:
                    logger.error(f"批量格式化失败: {error_msg}")
                    return False
            else:
                # 使用逐个文件模式，可以获得详细进度
                logger.info("使用逐个文件格式化模式")
                
                dart_files = self.find_dart_files()
                
                if not dart_files:
                    logger.warning("没有找到任何Dart文件")
                    return True
                
                # 处理每个文件
                failed_files_list = []
                
                for i, file_path in enumerate(dart_files, 1):
                    relative_path = file_path.relative_to(self.lib_path)
                    logger.info(f"[{i}/{len(dart_files)}] 格式化文件: {relative_path}")
                    
                    success, error_msg, changed = self.format_file(file_path)
                    
                    if not success:
                        failed_files_list.append((file_path, error_msg))
                    elif changed:
                        logger.info(f"  ✓ 文件已格式化")
                    
                    # 每处理50个文件显示一次进度
                    if i % 50 == 0:
                        logger.info(f"进度: {i}/{len(dart_files)} ({i/len(dart_files)*100:.1f}%)")
                
                # 输出统计结果
                end_time = time.time()
                duration = end_time - start_time
                
                logger.info("="*60)
                logger.info("格式化任务完成统计:")
                logger.info(f"扫描的文件数: {len(dart_files) + self.filtered_files}")
                logger.info(f"过滤的文件数: {self.filtered_files}")
                logger.info(f"处理的文件数: {len(dart_files)}")
                logger.info(f"成功格式化: {self.processed_files}")
                logger.info(f"文件已修改: {self.changed_files}")
                logger.info(f"跳过文件: {self.skipped_files}")
                logger.info(f"失败文件: {self.failed_files}")
                logger.info(f"耗时: {duration:.2f}秒")
                logger.info("="*60)
                
                # 输出失败文件列表
                if failed_files_list:
                    logger.error("以下文件格式化失败:")
                    for file_path, error_msg in failed_files_list:
                        logger.error(f"  {file_path}: {error_msg}")
                    return False
                
                if self.changed_files > 0:
                    logger.info(f"格式化完成！共修改了 {self.changed_files} 个文件")
                else:
                    logger.info("格式化完成！所有文件都已符合格式规范")
                
                return True
            
        except Exception as e:
            logger.error(f"执行过程中发生错误: {e}")
            return False

def main():
    """主函数"""
    import argparse
    
    # 解析命令行参数
    parser = argparse.ArgumentParser(description='Dart文件自动格式化工具')
    parser.add_argument('--mode', choices=['batch', 'individual'], default='batch',
                       help='格式化模式: batch(批量) 或 individual(逐个文件)')
    parser.add_argument('--path', type=str, 
                       help='指定lib目录路径（默认为脚本相对路径）')
    
    args = parser.parse_args()
    
    # 确定lib目录路径
    if args.path:
        lib_path = Path(args.path)
    else:
        # 获取脚本所在目录的父目录的父目录，即项目根目录
        script_dir = Path(__file__).parent
        project_root = script_dir.parent.parent
        lib_path = project_root / "lib"
    
    try:
        # 创建格式化器实例
        formatter = DartFileFormatter(str(lib_path))
        
        # 执行格式化任务
        use_batch_mode = (args.mode == 'batch')
        success = formatter.run(use_batch_mode=use_batch_mode)
        
        # 根据结果设置退出码
        sys.exit(0 if success else 1)
        
    except Exception as e:
        logger.error(f"程序执行失败: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()