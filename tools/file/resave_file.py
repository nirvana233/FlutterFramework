#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Dart文件重新保存脚本
用于遍历lib目录下的所有Dart文件，重新读取并保存每个文件
"""

import os
import sys
import logging
import subprocess
import re
from pathlib import Path
from typing import List, Tuple, Optional, Set
import time

# 配置日志
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('resave_file.log', encoding='utf-8'),
        logging.StreamHandler(sys.stdout)
    ]
)

logger = logging.getLogger(__name__)

class DartFileResaver:
    """Dart文件重新保存器"""
    
    # 定义需要跳过的文件和模式
    SKIP_PATTERNS = {
        # 自动生成的文件后缀
        '*.g.dart',           # 代码生成文件
        '*.freezed.dart',     # Freezed生成文件
        '*.mocks.dart',       # Mock生成文件
        '*.config.dart',      # 配置生成文件
        
        # 特定文件名
        'MyLocalization.dart',  # 本地化文件
        'firebase_options.dart',  # Firebase配置文件
        
        # 包含特定内容的文件（需要读取文件内容检查）
        '// GENERATED CODE',     # 生成代码标识
        '// 该文件由.*自动生成',   # 中文生成标识
        '// Generated by',      # 英文生成标识
        '// This file is generated',  # 另一种生成标识
    }
    
    def __init__(self, lib_path: str):
        """
        初始化重新保存器
        
        Args:
            lib_path: lib目录的绝对路径
        """
        self.lib_path = Path(lib_path)
        self.processed_files = 0
        self.failed_files = 0
        self.skipped_files = 0
        self.resaved_files = 0  # 重新保存的文件数
        self.filtered_files = 0  # 被过滤的文件数
        self.dart_cmd = self._find_dart_command()
        
        if not self.lib_path.exists():
            raise FileNotFoundError(f"lib目录不存在: {lib_path}")
        
        if not self.lib_path.is_dir():
            raise NotADirectoryError(f"指定路径不是目录: {lib_path}")
    
    def _find_dart_command(self) -> Optional[str]:
        """
        查找dart命令
        
        Returns:
            dart命令的路径，如果未找到则返回None
        """
        try:
            result = subprocess.run(['which', 'dart'], 
                                  capture_output=True, 
                                  text=True, 
                                  timeout=10)
            if result.returncode == 0:
                dart_path = result.stdout.strip()
                logger.info(f"找到dart命令: {dart_path}")
                return dart_path
            else:
                logger.error("未找到dart命令")
                return None
        except Exception as e:
            logger.error(f"查找dart命令失败: {e}")
            return None
    
    def _should_skip_file(self, file_path: Path) -> Tuple[bool, str]:
        """
        检查文件是否应该被跳过
        
        Args:
            file_path: 文件路径
            
        Returns:
            (是否跳过, 跳过原因)
        """
        # 检查文件名模式
        file_name = file_path.name
        
        # 检查特定文件名
        if file_name in ['MyLocalization.dart', 'firebase_options.dart']:
            return True, f"特定文件名: {file_name}"
        
        # 检查文件后缀模式
        if file_name.endswith('.g.dart'):
            return True, "代码生成文件(.g.dart)"
        if file_name.endswith('.freezed.dart'):
            return True, "Freezed生成文件(.freezed.dart)"
        if file_name.endswith('.mocks.dart'):
            return True, "Mock生成文件(.mocks.dart)"
        if file_name.endswith('.config.dart'):
            return True, "配置生成文件(.config.dart)"
        
        # 检查文件内容是否包含生成标识
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                # 只读取前几行来检查生成标识
                first_lines = []
                for i, line in enumerate(f):
                    if i >= 10:  # 只检查前10行
                        break
                    first_lines.append(line.strip())
                
                content_start = '\n'.join(first_lines)
                
                # 检查各种生成标识
                if '// GENERATED CODE' in content_start:
                    return True, "包含生成代码标识(GENERATED CODE)"
                if re.search(r'// 该文件由.*自动生成', content_start):
                    return True, "包含中文生成标识"
                if '// Generated by' in content_start:
                    return True, "包含生成标识(Generated by)"
                if '// This file is generated' in content_start:
                    return True, "包含生成标识(This file is generated)"
                if '// Code generated by' in content_start:
                    return True, "包含生成标识(Code generated by)"
                
        except Exception as e:
            logger.debug(f"检查文件内容时出错 {file_path}: {e}")
            # 如果无法读取文件内容，不跳过
            pass
        
        return False, ""
    
    def find_dart_files(self) -> List[Path]:
        """
        递归查找所有需要重新保存的Dart文件（排除自动生成的文件）
        
        Returns:
            需要重新保存的Dart文件路径列表
        """
        dart_files = []
        total_files = 0
        
        logger.info(f"开始扫描目录: {self.lib_path}")
        
        for file_path in self.lib_path.rglob("*.dart"):
            total_files += 1
            
            # 跳过隐藏文件和临时文件
            if any(part.startswith('.') for part in file_path.parts):
                logger.debug(f"跳过隐藏文件: {file_path}")
                self.filtered_files += 1
                continue
            
            # 检查是否应该跳过这个文件
            should_skip, skip_reason = self._should_skip_file(file_path)
            if should_skip:
                logger.debug(f"跳过文件: {file_path.relative_to(self.lib_path)} ({skip_reason})")
                self.filtered_files += 1
                continue
                
            if file_path.suffix.lower() == '.dart':
                dart_files.append(file_path)
        
        logger.info(f"扫描完成:")
        logger.info(f"  总Dart文件数: {total_files}")
        logger.info(f"  过滤的文件数: {self.filtered_files}")
        logger.info(f"  需要处理的文件数: {len(dart_files)}")
        
        return dart_files
    
    def resave_file(self, file_path: Path) -> Tuple[bool, str, bool]:
        """
        重新格式化并保存单个Dart文件
        
        Args:
            file_path: 文件路径
            
        Returns:
            (是否成功, 错误信息, 文件是否被重新保存)
        """
        try:
            # 检查文件是否为空
            if file_path.stat().st_size == 0:
                logger.warning(f"文件为空，跳过: {file_path}")
                self.skipped_files += 1
                return True, "文件为空", False
            
            if not self.dart_cmd:
                # 如果没有dart命令，则回退到简单的读写操作
                logger.warning(f"dart命令不可用，使用简单重新保存: {file_path}")
                with open(file_path, 'r', encoding='utf-8') as f:
                    content = f.read()
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(content)
                self.processed_files += 1
                self.resaved_files += 1
                return True, "简单重新保存", True
            
            # 先应用dart fix来添加const等优化（无论是否需要格式化都执行）
            fix_result = subprocess.run([
                self.dart_cmd, 'fix', '--apply',
                str(file_path)
            ], capture_output=True, text=True, timeout=30)
            
            fix_applied = "fixes made" in fix_result.stdout
            
            # 检查文件是否需要格式化
            check_result = subprocess.run([
                self.dart_cmd, 'format', 
                '--set-exit-if-changed',
                '--output=none',
                str(file_path)
            ], capture_output=True, text=True, timeout=30)
            
            # 退出码1表示文件需要格式化，0表示已经格式化好了
            needs_formatting = check_result.returncode == 1
            
            if not needs_formatting and not fix_applied:
                # 文件既不需要格式化，也没有应用fix，仍然需要"触摸"一下文件来更新修改时间
                with open(file_path, 'r', encoding='utf-8') as f:
                    content = f.read()
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(content)
                logger.debug(f"文件无需修改，仅更新修改时间: {file_path}")
                self.skipped_files += 1
                return True, "无需修改", False
            
            # 执行格式化（如果需要的话）
            format_result = subprocess.run([
                self.dart_cmd, 'format', 
                '--output=write',
                str(file_path)
            ], capture_output=True, text=True, timeout=30)
            
            if format_result.returncode == 0:
                if fix_applied or needs_formatting:
                    logger.debug(f"成功应用fix和/或格式化: {file_path}")
                    self.processed_files += 1
                    self.resaved_files += 1
                    return True, "", True
                else:
                    logger.debug(f"文件已处理但无修改: {file_path}")
                    self.skipped_files += 1
                    return True, "已处理", False
            else:
                error_msg = f"格式化失败: {format_result.stderr}"
                logger.error(f"格式化文件失败 {file_path}: {error_msg}")
                self.failed_files += 1
                return False, error_msg, False
                
        except subprocess.TimeoutExpired:
            error_msg = "格式化超时"
            logger.error(f"格式化文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
            
        except PermissionError as e:
            error_msg = f"权限错误: {e}"
            logger.error(f"重新保存文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
            
        except UnicodeDecodeError as e:
            error_msg = f"文件编码错误: {e}"
            logger.error(f"重新保存文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
            
        except Exception as e:
            error_msg = f"未知错误: {e}"
            logger.error(f"重新保存文件失败 {file_path}: {error_msg}")
            self.failed_files += 1
            return False, error_msg, False
    
    def batch_resave_directory(self) -> Tuple[bool, str]:
        """
        批量重新保存目录中的文件（排除自动生成的文件）
        
        Returns:
            (是否成功, 错误信息)
        """
        try:
            logger.info(f"开始批量重新保存目录: {self.lib_path}")
            
            # 获取需要重新保存的文件列表
            dart_files = self.find_dart_files()
            
            if not dart_files:
                logger.warning("没有找到需要重新保存的Dart文件")
                return True, "无文件需要处理"
            
            # 批量执行dart fix和dart format，提高性能
            if self.dart_cmd:
                file_paths = [str(file_path) for file_path in dart_files]
                
                # 1. 对目录应用dart fix
                logger.info("对目录应用dart fix...")
                fix_result = subprocess.run([
                    self.dart_cmd, 'fix', '--apply', str(self.lib_path)],
                    capture_output=True, text=True, timeout=120
                )
                if fix_result.stdout.strip():
                    logger.info(f"dart fix完成: {fix_result.stdout.strip()}")
                else:
                    logger.info("dart fix完成，没有发现需要修复的问题")
                
                # 2. 批量应用dart format
                logger.info("批量应用dart format...")
                format_result = subprocess.run([
                    self.dart_cmd, 'format'] + file_paths,
                    capture_output=True, text=True, timeout=120
                )
                if format_result.returncode == 0:
                    logger.info("dart format批量处理完成")
                    # 统计处理的文件数
                    self.processed_files = len(dart_files)
                    self.resaved_files = len(dart_files)
                else:
                    logger.error(f"dart format批量处理失败: {format_result.stderr}")
                    return False, f"批量格式化失败: {format_result.stderr}"
                    
            # 无需逐个处理文件，批量处理已完成
            failed_files_list = []
            
            if failed_files_list:
                error_msg = f"批量重新保存失败，共{len(failed_files_list)}个文件失败"
                logger.error(error_msg)
                return False, error_msg
            else:
                logger.info("批量重新保存完成")
                return True, "重新保存成功"
                
        except Exception as e:
            error_msg = f"批量重新保存异常: {e}"
            logger.error(error_msg)
            return False, error_msg
    
    def fast_batch_process(self, dart_files: List[Path]) -> Tuple[bool, str]:
        """
        快速批量处理文件
        
        Args:
            dart_files: 需要处理的文件列表
            
        Returns:
            (是否成功, 错误信息)
        """
        if not self.dart_cmd:
            return False, "dart命令不可用"
            
        file_paths = [str(file_path) for file_path in dart_files]
        
        try:
            # 1. 对目录应用dart fix（dart fix不支持多个文件参数）
            logger.info("对目录应用dart fix...")
            fix_result = subprocess.run([
                self.dart_cmd, 'fix', '--apply', str(dart_files[0].parent)],
                capture_output=True, text=True, timeout=120
            )
            if fix_result.stdout.strip():
                logger.info(f"dart fix完成: {fix_result.stdout.strip()}")
            else:
                logger.info("dart fix完成，没有发现需要修复的问题")
            
            # 2. 批量应用dart format
            logger.info("批量应用dart format...")
            format_result = subprocess.run([
                self.dart_cmd, 'format'] + file_paths,
                capture_output=True, text=True, timeout=120
            )
            
            if format_result.returncode == 0:
                logger.info("批量处理完成")
                self.processed_files = len(dart_files)
                self.resaved_files = len(dart_files)
                return True, "批量处理成功"
            else:
                return False, f"批量格式化失败: {format_result.stderr}"
                
        except Exception as e:
            return False, f"批量处理异常: {e}"
    
    def run(self, use_batch_mode: bool = True) -> bool:
        """
        执行重新保存任务
        
        Args:
            use_batch_mode: 是否使用批量模式（推荐）
        
        Returns:
            是否成功完成所有任务
        """
        start_time = time.time()
        logger.info("="*60)
        logger.info("开始执行Dart文件重新保存任务")
        logger.info("="*60)
        
        if not self.dart_cmd:
            logger.warning("dart命令不可用，将使用简单的文件重新保存模式")
        
        try:
            if use_batch_mode:
                # 使用批量模式，更高效
                logger.info("使用批量重新保存模式")
                success, error_msg = self.batch_resave_directory()
                
                if success:
                    end_time = time.time()
                    duration = end_time - start_time
                    
                    logger.info("="*60)
                    logger.info("批量重新保存完成统计:")
                    logger.info(f"处理目录: {self.lib_path}")
                    logger.info(f"过滤的文件数: {self.filtered_files}")
                    logger.info(f"重新保存的文件数: {self.resaved_files}")
                    logger.info(f"状态: {error_msg}")
                    logger.info(f"耗时: {duration:.2f}秒")
                    logger.info("="*60)
                    
                    return True
                else:
                    logger.error(f"批量重新保存失败: {error_msg}")
                    return False
            else:
                # 使用快速批量模式（推荐），individual模式也使用批量处理提高性能
                logger.info("使用快速批量重新保存模式")
                
                dart_files = self.find_dart_files()
                
                if not dart_files:
                    logger.warning("没有找到任何Dart文件")
                    return True
                
                # 使用快速批量处理
                success, error_msg = self.fast_batch_process(dart_files)
                
                if success:
                    end_time = time.time()
                    duration = end_time - start_time
                    
                    logger.info("="*60)
                    logger.info("快速批量处理完成统计:")
                    logger.info(f"扫描的文件数: {len(dart_files) + self.filtered_files}")
                    logger.info(f"过滤的文件数: {self.filtered_files}")
                    logger.info(f"处理的文件数: {len(dart_files)}")
                    logger.info(f"成功处理: {self.processed_files}")
                    logger.info(f"文件已重新保存: {self.resaved_files}")
                    logger.info(f"状态: {error_msg}")
                    logger.info(f"耗时: {duration:.2f}秒")
                    logger.info("="*60)
                    
                    return True
                else:
                    logger.error(f"快速批量处理失败: {error_msg}")
                    return False
            
        except Exception as e:
            logger.error(f"执行过程中发生错误: {e}")
            return False

def main():
    """主函数"""
    import argparse
    
    # 解析命令行参数
    parser = argparse.ArgumentParser(description='Dart文件重新保存工具')
    parser.add_argument('--mode', choices=['batch', 'individual'], default='batch',
                       help='重新保存模式: batch(批量) 或 individual(快速批量)')
    parser.add_argument('--path', type=str, 
                       help='指定lib目录路径（默认为脚本相对路径）')
    
    args = parser.parse_args()
    
    # 确定lib目录路径
    if args.path:
        lib_path = Path(args.path)
    else:
        # 获取脚本所在目录的父目录的父目录，即项目根目录
        script_dir = Path(__file__).parent
        project_root = script_dir.parent.parent
        lib_path = project_root / "lib"
    
    try:
        # 创建重新保存器实例
        resaver = DartFileResaver(str(lib_path))
        
        # 执行重新保存任务
        use_batch_mode = (args.mode == 'batch')
        success = resaver.run(use_batch_mode=use_batch_mode)
        
        # 根据结果设置退出码
        sys.exit(0 if success else 1)
        
    except Exception as e:
        logger.error(f"程序执行失败: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()